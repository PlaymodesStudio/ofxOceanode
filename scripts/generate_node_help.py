#!/usr/bin/env python3
"""Embed the reviewed node catalog and assistant guide without runtime data files.
Edit docs/node-help-catalog.json or docs/oceanode-assistant.md, then run this.
Only registered names appear in Help; catalog entries do not register nodes.
"""
import json
from pathlib import Path
root = Path(__file__).resolve().parents[1]
entries = json.loads((root / 'docs/node-help-catalog.json').read_text())
assert all(v['description'].strip() for v in entries.values())
chunks, group = [], {}
for key, entry in entries.items():
    group[key] = entry
    if len(json.dumps(group)) > 12000:
        chunks.append(group)
        group = {}
if group:
    chunks.append(group)
literals = ',\n'.join('R"oceanode_help(' + json.dumps(g, ensure_ascii=False, separators=(',', ':')) + ')oceanode_help"' for g in chunks)
(root / 'src/ofxOceanodeNodeHelpCatalog.h').write_text('''// Generated by scripts/generate_node_help.py; edit docs/node-help-catalog.json.
#pragma once
#include "ofMain.h"

inline const ofJson& ofxOceanodeNodeHelpCatalog() {
    static const ofJson catalog = [](){
        ofJson result = ofJson::object();
        // Separate chunks also support compilers with small string-literal limits.
        for(const char* chunk : {
''' + literals + '''
        }) result.update(ofJson::parse(chunk));
        return result;
    }();
    return catalog;
}
inline const ofJson* ofxOceanodeNodeHelpEntry(const std::string& name) {
    const auto& catalog = ofxOceanodeNodeHelpCatalog();
    auto item = catalog.find(name);
    if(item != catalog.end()) return &*item;
    // Dynamic type families (Router, Buffer, configured fixtures, synthdefs).
    const ofJson* best = nullptr;
    size_t length = 0;
    for(auto it = catalog.begin(); it != catalog.end(); ++it) {
        const auto& key = it.key();
        if(!key.empty() && key.back() == ' ' && key.size() > length && name.compare(0, key.size(), key) == 0) {
            best = &it.value();
            length = key.size();
        }
    }
    return best;
}
inline std::string ofxOceanodeNodeHelpDescription(const std::string& name) {
    const auto* entry = ofxOceanodeNodeHelpEntry(name);
    return entry ? entry->value("description", std::string()) : "";
}
''')
prompt = (root / 'docs/oceanode-assistant.md').read_text()
(root / 'src/Managers/ofxOceanodeHelpPrompt.h').write_text(
    '// Generated by scripts/generate_node_help.py.\n#pragma once\n'
    'inline const char* ofxOceanodeHelpPrompt() { return R"oceanode_help(' + prompt + ')oceanode_help"; }\n')
print(f'Embedded {len(entries)} node descriptions and assistant guide')
